#!/usr/bin/env bash
# Regenerate backend/constraints.txt: installs the latest versions allowed by the backend's
# requirements files (runtime, test/lint and packaging) into a throwaway venv and freezes it.
# Run this to upgrade dependencies on purpose, then commit the diff and re-run ./bin/setup.sh.
# Upgrades can move simulation results, so replay a save before and after (see
# .agents/skills/replay-ab) when numpy, scipy or numba change.
#
# PYTHON overrides the interpreter (default python3).
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cd "$REPO_ROOT/backend"
"${PYTHON:-python3}" -m venv "$tmp/venv"
"$tmp/venv/bin/python" -m pip install -q --upgrade pip
"$tmp/venv/bin/python" -m pip install -q -r requirements.txt -r requirements-build.txt

{
  cat <<'HEADER'
# Exact versions for every backend dependency (runtime, test, lint and packaging), so every
# worktree, CI and the packaged binary simulate with the same numpy/scipy/numba. Replay
# numbers are only comparable across runs that used the same versions.
#
# Applied as a constraint, not a requirement: install with
#   pip install -r requirements.txt -c constraints.txt
# (bin/setup.sh and CI do this). Packages a platform doesn't need are simply ignored.
#
# Generated by bin/pin_deps.sh -- don't edit by hand. To upgrade, run it and commit the diff.
HEADER
  "$tmp/venv/bin/python" -m pip freeze --exclude-editable
} > constraints.txt
echo "Wrote backend/constraints.txt -- review with: git diff backend/constraints.txt"
